import {test,expect} from '@playwright/test';
import * as THREE from 'three';
import {buildingHeight,plotPosition} from '../src/engine/cityGeometry.js';
import {toDisplayNode} from '../src/engine/gridReferences.js';

test('batched city stays small and supports orbit, pan, walking and every 2D workspace',async({page,request})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await request.post('/api/start',{data:{seed:42,automatic_events:false}});
  await page.goto('/');
  const viewport=page.getByTestId('city-viewport');
  await expect(viewport).toHaveAttribute('data-draw-calls',/\d+/,{timeout:30000});
  expect(Number(await viewport.getAttribute('data-draw-calls'))).toBeLessThan(250);
  await page.waitForTimeout(1800);
  const before=await viewport.getAttribute('data-camera-position');
  await page.mouse.move(1020,470);await page.mouse.down();await page.mouse.move(1180,540,{steps:18});await page.mouse.up();
  await expect.poll(()=>viewport.getAttribute('data-camera-position')).not.toBe(before);
  const turned=await viewport.getAttribute('data-camera-position');
  await page.mouse.move(1020,470);await page.mouse.down({button:'right'});await page.mouse.move(950,500,{steps:12});await page.mouse.up({button:'right'});
  await expect.poll(()=>viewport.getAttribute('data-camera-position')).not.toBe(turned);
  await page.waitForTimeout(1000);
  const settled=(await viewport.getAttribute('data-camera-position')).split(',').map(Number);
  await page.waitForTimeout(1600);
  const polled=(await viewport.getAttribute('data-camera-position')).split(',').map(Number);
  expect(Math.hypot(...settled.map((value,i)=>value-polled[i]))).toBeLessThan(.15);
  await request.post('/api/simulation/step');
  await page.waitForTimeout(1400);
  const stepped=(await viewport.getAttribute('data-camera-position')).split(',').map(Number);
  expect(Math.hypot(...polled.map((value,i)=>value-stepped[i]))).toBeLessThan(.15);
  await page.mouse.wheel(0,-180);
  await expect.poll(()=>viewport.getAttribute('data-camera-position')).not.toBe(polled.map(n=>n.toFixed(2)).join(','));
  await page.getByRole('button',{name:'Walk streets',exact:true}).click();
  await expect(viewport).toHaveAttribute('data-camera-mode','street');
  await expect.poll(async()=>Number((await viewport.getAttribute('data-camera-position')).split(',')[1])).toBeLessThan(2);
  const walking=await viewport.getAttribute('data-camera-position');
  await page.keyboard.down('KeyW');await page.waitForTimeout(1000);await page.keyboard.up('KeyW');
  await expect.poll(()=>viewport.getAttribute('data-camera-position')).not.toBe(walking);
  const look=await viewport.getAttribute('data-camera-direction');
  await page.mouse.move(1000,450);await page.mouse.down();await page.mouse.move(1130,460,{steps:12});await page.mouse.up();
  await expect.poll(()=>viewport.getAttribute('data-camera-direction')).not.toBe(look);
  await page.screenshot({path:'e2e-artifacts/city-street-level.png',fullPage:true});
  await page.getByRole('button',{name:'Map overview',exact:true}).click();
  await expect(viewport).toHaveAttribute('data-camera-mode','map');
  for(const label of ['MEDICAL DISPATCH','CITY MAP','ROUTE LAB','DISASTERS','AMBULANCE','HEATMAP','POLICE OPERATIONS','METRICS','DIAGNOSTICS','CITY EVENTS'])await expect(page.getByRole('button',{name:label,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'CITY MAP',exact:true}).click();
  for(const name of ['Sector Labels','Sector IDs','Road Costs','Sector Population','Ambulance Coverage','Police Presence'])await expect(page.getByLabel(name,{exact:true})).toBeAttached();
  await page.getByLabel('Sector Labels',{exact:true}).check();
  await page.getByLabel('Road Costs',{exact:true}).check();
  await page.getByLabel('Sector Population',{exact:true}).check();
  await page.getByRole('button',{name:'Close workspace',exact:true}).click();
  await page.getByRole('button',{name:'Orbit city',exact:true}).click();
  await page.waitForTimeout(1800);
  await page.screenshot({path:'e2e-artifacts/city-overview.png',fullPage:true});
  const state=await (await request.get('/api/state')).json();
  const target=state.graph.nodes.filter(n=>n.node_type!=='EMPTY').sort((a,b)=>(b.row+b.col)-(a.row+a.col))[0];
  const bounds=await page.locator('canvas').boundingBox();
  const camera=new THREE.PerspectiveCamera(50,bounds.width/bounds.height,.1,450);
  camera.position.fromArray((await viewport.getAttribute('data-camera-position')).split(',').map(Number));
  camera.quaternion.fromArray((await viewport.getAttribute('data-camera-direction')).split(',').map(Number)).normalize();camera.updateMatrixWorld();
  const [x,z]=plotPosition(toDisplayNode(target)),point=new THREE.Vector3(x,buildingHeight(target)-.3,z).project(camera);
  await page.mouse.click(bounds.x+(point.x+1)*bounds.width/2,bounds.y+(1-point.y)*bounds.height/2);
  await expect(page.locator('.right-panel')).toContainText(`Sector ${target.label}`);
  await expect(page.getByRole('button',{name:'Focus selected',exact:true})).toBeEnabled();
  expect(errors).toEqual([]);
});
